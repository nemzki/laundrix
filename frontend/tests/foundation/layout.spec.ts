import { expect, test } from '@playwright/test'

for (const role of ['admin', 'staff']) for (const width of [320, 768, 1440]) {
  test(`${role} foundation at ${width}px: layout, dialog, navigation and CSP`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(() => {
      Object.assign(window, { violations: [] as string[] })
      document.addEventListener('securitypolicyviolation', event => (window as unknown as { violations: string[] }).violations.push(`${event.effectiveDirective}: ${event.blockedURI}`))
    })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(`/foundation.html?role=${role}`)
    await expect(page.getByRole('heading', { name: 'Frontend foundation' })).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.fonts.check('400 14px "Laundrix Foundation Geist"'))).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const sidebar = page.locator('.fx-sidebar')
    if (width < 768) {
      await expect(sidebar).toBeHidden()
      const menu = page.getByRole('button', { name: 'Open navigation' })
      await menu.click()
      await expect(page.getByRole('dialog')).toBeVisible()
      await page.keyboard.press('Tab')
      expect(await page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(menu).toBeFocused()
    } else {
      await expect(sidebar).toBeVisible()
      expect(await sidebar.evaluate(element => element.getBoundingClientRect().top)).toBe(0)
      const usableWidth = await page.evaluate(() => document.documentElement.clientWidth)
      expect(await page.locator('.fx-main').evaluate(element => element.getBoundingClientRect().width)).toBe(usableWidth - 256)
    }
    const trigger = page.getByRole('button', { name: 'Open dialog', exact: true })
    await trigger.click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.locator('#laundrix-foundation-portals')).toHaveClass('lx-react lx-foundation')
    expect(await page.getByRole('dialog').evaluate(element => getComputedStyle(element).fontFamily)).toContain('Laundrix Foundation Geist')
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await page.getByRole('button', { name: 'Open confirmation' }).click()
    await expect(page.getByRole('alertdialog')).toBeVisible()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('alertdialog')).toHaveCount(0)
    await page.getByLabel('Search components').fill('not available')
    await expect(page.getByRole('heading', { name: 'No results' })).toBeVisible()
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    await expect(page.getByRole('cell', { name: 'Application shell', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Show notification' }).click()
    await expect(page.getByText('Component preview notification. No operation was performed.')).toBeVisible()
    await page.getByRole('button', { name: 'Dismiss notification' }).click()
    await expect(page.getByText('Component preview notification. No operation was performed.')).toHaveCount(0)
    const invalid = page.getByLabel('Validation example')
    await expect(invalid).toHaveAttribute('aria-invalid', 'true')
    await expect(invalid).toHaveAttribute('aria-describedby', /-error$/)
    await page.getByRole('button', { name: 'Check legacy portal' }).click()
    await expect(page.locator('#laundrix-react-portals')).toHaveClass('lx-react')
    await expect(page.getByRole('dialog', { name: 'Legacy portal check' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect.poll(() => page.evaluate(() => getComputedStyle(document.body).overflow)).not.toBe('hidden')
    expect(await page.evaluate(() => (window as unknown as { violations: string[] }).violations)).toEqual([])
    expect(errors).toEqual([])
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0) })
    await expect.poll(() => page.evaluate(() => scrollY)).toBe(0)
    await page.screenshot({ path: `test-results/foundation-${role}-${width}.png` })
  })
}
