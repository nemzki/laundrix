test('configured reference-required method and payment notes persist through the original ledger', async ({ page }) => {
  await login(page)
  const csrf = await page.locator('#wizard').getAttribute('data-csrf')
  const response = await page.request.post('/payments/methods', { headers: { 'X-CSRFToken': csrf! }, data: { label: 'Reference check', requires_reference: true } })
  expect(response.status()).toBe(200)
  const created = await response.json() as { id: number; code: string }
  try {
    await page.reload(); await existingCustomer(page); await wash(page); await next(page, 4)
    await arrangement(page, 'full'); await method(page, created.code)
    await page.locator('#btn-next').click()
    await expect(page.locator(`[data-error-for="payment:${created.code}"]`)).toContainText('reference number is required')
    await page.locator(`[data-pay-ref="${created.code}"]`).fill('REF_31/AB')
    await page.locator(`[data-pay-notes="${created.code}"]`).fill('Original ledger note')
    await next(page, 5)
    const { redirect } = await confirm(page)
    await page.goto(redirect.replace('/confirmation', ''))
    await expect(page.getByText('Original ledger note', { exact: true })).toBeVisible()
  } finally {
    const disabled = await page.request.post(`/payments/methods/${created.id}/toggle`, { headers: { 'X-CSRFToken': csrf! } })
    expect(disabled.status()).toBe(200)
  }
})

test('original settings control partial/pay-later choices and enabled GCash visibility', async ({ page }) => {
  await login(page)
  const csrf = await page.locator('#wizard').getAttribute('data-csrf')
  const settingsResponse = await page.request.get('/payments/settings')
  const state = await page.evaluate(html => {
    const doc = new DOMParser().parseFromString(html, 'text/html')
    const form = doc.querySelector('form[action="/payments/settings"]') as HTMLFormElement
    const values = Object.fromEntries(new FormData(form))
    const row = [...doc.querySelectorAll('tr')].find(row => row.querySelector('strong')?.textContent === 'GCash')!
    return { values, toggleUrl: row.querySelector('form')!.getAttribute('action')! }
  }, await settingsResponse.text())
  try {
    const saved = await page.request.post('/payments/settings', { headers: { 'X-CSRFToken': csrf! }, data: { ...state.values, partial_enabled: false, pay_later_enabled: false } })
    expect(saved.status()).toBe(200)
    const disabled = await page.request.post(state.toggleUrl, { headers: { 'X-CSRFToken': csrf! } })
    expect(disabled.status()).toBe(200)
    await page.reload()
    await expect(page.locator('input[value=partial], input[value=pay_later], input[data-pay-method][value=gcash]')).toHaveCount(0)
    await existingCustomer(page); await wash(page); await next(page, 4)
    await arrangement(page, 'full'); await method(page, 'cash'); await next(page, 5)
  } finally {
    const restored = await page.request.post('/payments/settings', { headers: { 'X-CSRFToken': csrf! }, data: state.values })
    expect(restored.status()).toBe(200)
    const enabled = await page.request.post(state.toggleUrl, { headers: { 'X-CSRFToken': csrf! } })
    expect(enabled.status()).toBe(200)
  }
})
