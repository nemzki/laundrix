import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, role: 'admin' | 'staff' = 'admin') {
  await page.goto('/auth/login')
  if (role === 'staff') await page.getByRole('tab', { name: 'Staff', exact: true }).click()
  await page.locator(`#${role}-identifier`).fill(role === 'admin' ? 'browseradmin' : 'staff@example.test')
  await page.locator(`#${role}-password`).fill('Browser-Test-Password!42')
  await page.locator(`form[data-auth-form=${role}] button[type=submit]`).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.goto('/orders/new')
}
async function step(page: Page, number: number) {
  await expect(page.locator(`.wstep[data-step="${number}"]`)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function next(page: Page, number: number) { await page.locator('#btn-next').click(); await step(page, number) }
async function existingCustomer(page: Page) {
  await page.locator('#cust-search').fill('Customer 00')
  await page.locator('#cust-results').getByRole('button', { name: /Customer 00/ }).click()
  await next(page, 2)
}
async function wash(page: Page, quantity = '1') {
  await page.locator('input[data-code=wash]').locator('..').click()
  await next(page, 3)
  await page.locator('[data-detail$=":quantity"]').fill(quantity)
}
async function arrangement(page: Page, value: string) { await page.locator(`input[name=arrangement][value=${value}]`).locator('..').click() }
async function method(page: Page, code: string) { await page.locator(`input[data-pay-method][value=${code}]`).locator('..').click() }
async function confirm(page: Page) {
  page.once('dialog', dialog => dialog.accept())
  const response = page.waitForResponse(response => response.url().endsWith('/orders/new/confirm') && response.request().method() === 'POST')
  await page.locator('#btn-confirm').click()
  const result = await response
  expect(result.status()).toBe(200)
  const body = result.request().postDataJSON()
  expect(body.sms_consent).toBe(false)
  expect(body.submission_token).toMatch(/^[A-Za-z0-9_-]{16,64}$/)
  expect(body).not.toHaveProperty('dueAt')
  expect(body).not.toHaveProperty('ready_time')
  await expect(page).toHaveURL(/\/orders\/[^/]+\/confirmation$/)
  return { body, redirect: new URL(page.url()).pathname }
}

