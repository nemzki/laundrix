import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, role: 'admin' | 'staff') {
  await page.goto('/auth/login', { waitUntil: 'domcontentloaded' })
  if (role === 'staff') await page.getByRole('tab', { name: 'Staff', exact: true }).click()
  await page.locator(`#${role}-identifier`).fill(role === 'admin' ? 'browseradmin' : 'staff@example.test')
  await page.locator(`#${role}-password`).fill('Browser-Test-Password!42')
  await page.locator(`form[data-auth-form=${role}] button[type=submit]`).click()
  await expect(page.locator('#laundrix-dashboard')).toHaveAttribute('data-ready', 'true')
  await page.goto('/settings', { waitUntil: 'domcontentloaded' })
}

for (const role of ['admin','staff'] as const) for (const width of [320,768,1440]) {
  test(`profile edit, preview, reset and persistence: ${role} ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
    await login(page, role)
    await expect(page).toHaveTitle('Personal Settings | Laundrix')
    const name = page.getByLabel('Full Name', { exact: true })
    const original = await name.inputValue()
    const updated = `${role.toUpperCase()} Profile ${width}`
    await name.fill(''); await page.getByRole('button', { name: 'Save Changes', exact: true }).click()
    await expect(page.locator('#profile-name-error')).toContainText('2 to 150')
    await name.fill(updated)
    await page.locator('#profile-picture').setInputFiles({ name: 'invalid.png', mimeType: 'image/png', buffer: Buffer.from('not-an-image') })
    await expect(page.locator('[data-picture-error]')).toContainText('could not be previewed')
    // Browser-generated bitmap only for the isolated test fixture, not application data.
    const png = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width=64; canvas.height=64; const context=canvas.getContext('2d')!; context.fillStyle='#3478f6'; context.fillRect(0,0,64,64); return canvas.toDataURL('image/png').split(',')[1] })
    const chooser = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: 'Edit Profile Picture', exact: true }).click()
    await (await chooser).setFiles({ name: 'profile.png', mimeType: 'image/png', buffer: Buffer.from(png,'base64') })
    await expect(page.locator('[data-avatar-preview]')).toBeVisible()
    await expect(page.locator('[data-avatar-preview]')).toHaveAttribute('src', /^data:image\/png/)
    await page.getByRole('link', { name: 'Cancel', exact: true }).click()
    await expect(name).toHaveValue(original)
    await expect(page.locator('[data-avatar-preview]')).toBeHidden()
    await name.fill(`  ${updated}  `)
    await page.locator('#profile-picture').setInputFiles({ name: 'profile.png', mimeType: 'image/png', buffer: Buffer.from(png,'base64') })
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click()
    await expect(page.locator('[data-profile-name]')).toHaveText(updated)
    await expect(page.locator('.flash-success')).toContainText('updated')
    const avatar = await page.locator('[data-avatar-original] img').getAttribute('src')
    expect(avatar).toMatch(/^\/settings\/avatar\/avatar-[a-f0-9]{32}\.png$/)
    await page.reload({ waitUntil: 'domcontentloaded' })
    await expect(name).toHaveValue(updated)
    await expect(page.locator('[data-avatar-original] img')).toHaveAttribute('src', avatar!)
    await expect(page.locator('#app-sidebar .lx-sidebar__user-name')).toHaveText(updated)
    await expect(page.locator('#app-sidebar img.lx-sidebar__avatar')).toHaveAttribute('src', avatar!)
    const verification = await page.locator('[aria-labelledby=verification-heading]').boundingBox()
    const appearance = await page.locator('[aria-labelledby=appearance-heading]').boundingBox()
    if (width >= 1024) expect(verification!.y).toBeCloseTo(appearance!.y,1)
    else expect(appearance!.y).toBeGreaterThan(verification!.y)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/profile-editing/${role}-dark-${width}.png`, fullPage: true })
    await page.goto('/dashboard/', { waitUntil: 'domcontentloaded' })
    await expect(page.locator('#laundrix-dashboard')).toHaveAttribute('data-ready','true')
    if (width < 768) await page.getByRole('button', { name: 'More', exact: true }).click()
    await expect(page.locator('.dashboard-user strong').first()).toHaveText(updated)
    await expect(page.locator('.dashboard-user img').first()).toHaveAttribute('src', avatar!)
    await page.goto('/orders/', { waitUntil: 'domcontentloaded' })
    await expect(page.locator('#app-sidebar .lx-sidebar__user-name')).toHaveText(updated)
    await page.goto('/settings', { waitUntil: 'domcontentloaded' })
    await page.getByLabel('Remove Picture and Use Default Avatar').check()
    await page.getByRole('button', { name: 'Save Changes', exact: true }).click()
    await expect(page.locator('[data-avatar-original] img')).toHaveCount(0)
    await expect(page.locator('[data-avatar-original] .ps-avatar')).toBeVisible()
    expect((await page.request.get(avatar!)).status()).toBe(404)
    // Restore the isolated fixture name so the original role regressions can run afterward.
    await name.fill(original); await page.getByRole('button', { name: 'Save Changes', exact: true }).click()
    await page.locator('[data-theme-preferences] [data-theme-option=light]').click()
    await expect(page.locator('.ps-card').first()).toHaveCSS('background-color','rgb(255, 255, 255)')
    await page.screenshot({ path: `test-results/profile-editing/${role}-light-${width}.png`, fullPage: true })
    expect(errors).toEqual([])
  })
}
