import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, role: 'admin' | 'staff') {
  await page.goto('/auth/login', { waitUntil: 'domcontentloaded' })
  if (role === 'staff') await page.getByRole('tab', { name: 'Staff', exact: true }).click()
  await page.locator(`#${role}-identifier`).fill(role === 'admin' ? 'browseradmin' : 'staff@example.test')
  await page.locator(`#${role}-password`).fill('Browser-Test-Password!42')
  await page.locator(`form[data-auth-form=${role}] button[type=submit]`).click()
  await expect(page.locator('#laundrix-dashboard')).toHaveAttribute('data-ready', 'true')
}

for (const role of ['admin', 'staff'] as const) for (const width of [320, 768, 1440]) {
  test(`Personal Settings own profile, appearance and logout: ${role} ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await login(page, role)
    if (width < 768) await page.getByRole('button', { name: 'More', exact: true }).click()
    const gear = page.getByRole('link', { name: 'Personal Settings', exact: true }).filter({ visible: true }).first()
    await expect(gear).toHaveAttribute('title', 'Personal Settings')
    await expect(gear).toHaveAttribute('href', '/settings')
    await expect(page.locator('[data-theme-picker]')).toHaveCount(0)
    await gear.focus(); await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/\/settings$/)
    await expect(page.getByRole('heading', { name: 'Personal Settings', exact: true })).toBeVisible()
    await expect(page.locator('[data-profile-name]')).toHaveText(role === 'admin' ? 'Browser Admin' : 'Sam Cruz')
    await expect(page.locator('[data-profile-email]')).toHaveText(role === 'admin' ? 'admin@example.test' : 'staff@example.test')
    await expect(page.locator('main')).not.toContainText(role === 'admin' ? 'staff@example.test' : 'admin@example.test')
    await expect(page.getByRole('heading', { name: 'My Profile', exact: true })).toBeVisible()
    await expect(page.locator('[data-personal-settings]')).toContainText('Identity verification is not enabled for this installation.')
    await expect(page.locator('main input[name=full_name]')).toHaveCount(1)
    await expect(page).toHaveTitle('Personal Settings | Laundrix')
    await expect(page.locator('.lx-sidebar__nav a[href="/settings"]')).toHaveCount(0)
    const content = await page.locator('.content').boundingBox()
    await page.screenshot({ path: `test-results/personal-settings/${role}-light-${width}.png`, fullPage: true })
    const choices = page.locator('[data-theme-preferences]')
    await expect(choices.locator('[data-theme-option=system]')).toHaveAttribute('aria-checked', 'true')
    await choices.locator('[data-theme-option=dark]').click()
    await expect(page.locator('html')).toHaveAttribute('data-lx-theme', 'dark')
    await expect(page.locator('.ps-card').first()).toHaveCSS('background-color', 'rgb(30, 41, 59)')
    expect(await page.evaluate(() => localStorage.getItem('laundrix-theme'))).toBe('dark')
    await page.reload({ waitUntil: 'domcontentloaded' })
    await expect(choices.locator('[data-theme-option=dark]')).toHaveAttribute('aria-checked', 'true')
    await page.screenshot({ path: `test-results/personal-settings/${role}-dark-${width}.png`, fullPage: true })
    for (const route of ['/orders/', '/payments/outstanding']) {
      await page.goto(route, { waitUntil: 'domcontentloaded' })
      await expect(page.locator('html')).toHaveAttribute('data-lx-theme', 'dark')
    }
    await page.goto('/settings', { waitUntil: 'domcontentloaded' })
    expect((await page.locator('.content').boundingBox())!.width).toBeCloseTo(content!.width, 1)
    await choices.locator('[data-theme-option=dark]').focus()
    await page.keyboard.press('Home')
    await expect(choices.locator('[data-theme-option=light]')).toBeFocused()
    await expect(page.locator('html')).toHaveAttribute('data-lx-theme', 'light')
    await page.keyboard.press('End')
    await expect(choices.locator('[data-theme-option=system]')).toBeFocused()
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(page.locator('html')).toHaveAttribute('data-lx-theme', 'dark')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator('section[aria-labelledby=security-heading]').getByRole('button', { name: 'Logout', exact: true }).click()
    await expect(page).toHaveURL(/\/$/)
    await expect(page.locator('html')).toHaveAttribute('data-theme-preference', 'system')
    await expect(page.locator('html')).toHaveAttribute('data-lx-theme', 'dark')
    expect((await page.request.get('/settings', { maxRedirects: 0 })).status()).toBe(302)
    expect(errors).toEqual([])
  })
}

test('server dashboard gear and settings page work when the React bundle is blocked', async ({ page }) => {
  await page.route('**/react-dashboard/dashboard.js', route => route.abort())
  await page.goto('/auth/login', { waitUntil: 'domcontentloaded' })
  await page.locator('#admin-identifier').fill('browseradmin')
  await page.locator('#admin-password').fill('Browser-Test-Password!42')
  await page.locator('form[data-auth-form=admin] button[type=submit]').click()
  await expect(page.locator('#laundrix-dashboard')).toHaveAttribute('data-renderer', 'server')
  await page.getByRole('link', { name: 'Personal Settings', exact: true }).filter({ visible: true }).first().click()
  await expect(page.locator('[data-personal-settings]')).toBeVisible()
})
