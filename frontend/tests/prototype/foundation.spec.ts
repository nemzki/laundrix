import { expect, test } from '@playwright/test'

for (const role of ['admin', 'staff']) for (const width of [320, 768, 1440]) {
  test(`${role} reference foundation at ${width}px`, async ({ page }) => {
    const errors: string[] = []; const apiRequests: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (['fetch', 'xhr'].includes(request.resourceType())) apiRequests.push(request.url()) })
    await page.setViewportSize({ width, height: 900 })
    await page.goto(`/prototype.html?role=${role}`)
    await expect(page.getByRole('heading', { name: 'Frontend foundation' })).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.fonts.check('400 14px Geist'))).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const navigation = page.getByRole('navigation', { name: 'Main navigation' })
    if (width < 768) {
      await expect(navigation).toBeHidden()
      const trigger = page.getByRole('button', { name: 'Toggle navigation' })
      await trigger.click()
      await expect(page.getByRole('dialog')).toBeVisible()
      await expect.poll(() => page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
      await page.keyboard.press('Tab')
      await expect.poll(() => page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
      await page.keyboard.press('Escape')
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(trigger).toBeFocused()
    } else {
      await expect(navigation).toBeVisible()
      const sizes = await page.locator('[data-slot=sidebar-inset]').evaluate(element => ({ width: element.getBoundingClientRect().width, total: document.documentElement.clientWidth }))
      expect(sizes.width).toBe(sizes.total - 256)
      await expect(navigation.getByRole('link', { name: 'Admin presentation' })).toHaveCount(role === 'admin' ? 1 : 0)
    }
    const trigger = page.getByRole('button', { name: 'Open dialog', exact: true })
    await trigger.click()
    await expect(page.getByRole('dialog', { name: 'Dialog preview' })).toBeVisible()
    await expect.poll(() => page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
    for (let step = 0; step < 3; step++) {
      await page.keyboard.press('Tab')
      await expect.poll(() => page.evaluate(() => Boolean(document.activeElement?.closest('[role=dialog]')))).toBe(true)
    }
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await page.getByRole('button', { name: 'Open confirmation' }).click()
    await expect(page.getByRole('alertdialog')).toBeVisible()
    await expect(page.getByRole('button', { name: 'No operation connected' })).toBeDisabled()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('alertdialog')).toHaveCount(0)
    await page.getByRole('combobox', { name: 'Component type' }).click()
    await page.getByRole('option', { name: 'Tables only' }).click()
    await expect(page.getByRole('cell', { name: 'Page layout', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    await page.getByLabel('Search components').fill('not available')
    await expect(page.getByText('No matching records', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Clear', exact: true }).click()
    await expect(page.getByRole('cell', { name: 'Page layout', exact: true })).toBeVisible()
    await expect(page.getByLabel('Validation example')).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByLabel('Validation example')).toHaveAttribute('aria-describedby', /-error$/)
    await page.getByRole('button', { name: 'Show notification' }).click()
    await expect(page.getByText('Component preview notification. No operation was performed.')).toBeVisible()
    expect(await page.evaluate(() => document.cookie)).not.toContain('sidebar_state')
    expect(errors).toEqual([]); expect(apiRequests).toEqual([])
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0) })
    await page.screenshot({ path: `test-results/${role}-${width}.png` })
  })
}
